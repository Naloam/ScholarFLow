"""Phase A1 — paper blueprint (FARS-style structured intermediate representation).

The blueprint is the single source of truth for the paper layer: every section
knows its claims, and every claim is BOUND to deterministic evidence (a metrics
path + verbatim numbers), figures/tables generated by ``tables_figures`` (never
hand-written), and literature entries carrying real abstracts/methods/results
(the June drafts' "related work = title listing" came from the writer never
seeing any of this).

Two layers:
- ``build_skeleton`` — deterministic: claims from metrics/verdict, tables,
  figures, references with digests. No LLM.
- ``plan_blueprint``   — ONE LLM call to plan the argumentative structure
  (title direction, claim ordering per section, related-work thematic
  grouping, discussion angles). Output is validated against the skeleton:
  unknown claim ids / unknown reference markers are dropped, never trusted.
"""
from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any

from services.research_harness import citation, evidence, tables_figures
from services.llm.client import chat
from services.llm.response_utils import get_message_content

logger = logging.getLogger(__name__)

SECTIONS = ("related_work", "methods", "experiments", "discussion", "conclusion", "introduction", "abstract")


# --------------------------------------------------------------------------- #
# Deterministic skeleton
# --------------------------------------------------------------------------- #


def _verdict_summary(metrics: dict[str, Any], hypothesis: dict[str, Any] | None) -> dict[str, Any]:
    fv = evidence.full_verdict(metrics, hypothesis)
    return {
        "verdict": fv["verdict"],
        "primary_metric": fv["primary_metric"],
        "primary_beats_baseline": fv["primary_beats_baseline"],
        "downgrade_reasons": fv.get("downgrade_reasons", []),
        "kill_criteria": [
            {"criterion": k["criterion"], "tripped": k["tripped"]} for k in fv.get("kill_criteria", [])
        ],
    }


def _deterministic_claims(metrics: dict[str, Any]) -> list[dict[str, Any]]:
    """One claim per dataset comparison + significance + diagnostics, each bound
    to its verbatim metrics source. These are the ONLY numbers the paper may
    state; the writer's job is narrative, not arithmetic."""
    claims: list[dict[str, Any]] = []
    bc = metrics.get("baseline_comparison") or {}
    for i, d in enumerate(bc.get("datasets") or []):
        if not isinstance(d, dict):
            continue
        claims.append({
            "id": f"cmp_{i}",
            "section": "experiments",
            "text_hint": f"{d.get('dataset')}: proposed {d.get('proposed_metric')} vs baseline {d.get('baseline_metric')} "
                         f"(Δ{d.get('delta', 0):+.6f}, beats={d.get('beats_baseline')})",
            "evidence": {
                "source": f"metrics.json:baseline_comparison.datasets[{i}]",
                "dataset": d.get("dataset"),
                "proposed": d.get("proposed_metric"),
                "baseline": d.get("baseline_metric"),
                "delta": d.get("delta"),
            },
        })
    for i, t in enumerate((metrics.get("statistics") or {}).get("significance_tests") or []):
        claims.append({
            "id": f"sig_{i}",
            "section": "experiments",
            "text_hint": f"significance: {t.get('detail')} significant={t.get('significant')}",
            "evidence": {"source": f"metrics.json:statistics.significance_tests[{i}]", "significant": t.get("significant")},
        })
    for metric, per_ds in (metrics.get("abstention_metrics") or {}).items():
        for ds, systems in per_ds.items():
            props = {k: v for k, v in systems.items() if "proposed" in k.lower()}
            if props:
                claims.append({
                    "id": f"diag_{metric}_{ds}",
                    "section": "experiments",
                    "text_hint": f"{metric} on {ds}: {props}",
                    "evidence": {"source": f"metrics.json:abstention_metrics.{metric}.{ds}", "values": props},
                })
    return claims


def build_skeleton(
    project_id: str,
    idea: str,
    selected: dict[str, Any],
    metrics: dict[str, Any],
    papers: list[dict[str, Any]],
    workspace_root: Path | None = None,
) -> dict[str, Any]:
    root = Path(workspace_root) if workspace_root is not None else _ws_root()
    proj = root / project_id
    refs = citation.build_journal_references(papers, draft_text=None, max_refs=30)
    ref_entries = []
    for r in refs:
        p = next((x for x in papers if citation.titles_match(r["title"], x.get("title") or "")), {})
        ref_entries.append({
            "marker": r["marker"],
            "title": r["title"],
            "entry_gbt": r["entry"],
            "year": p.get("year"),
            "venue": p.get("venue"),
            "abstract_digest": (p.get("abstract") or "")[:600],
            "methods": (p.get("methods") or [])[:2],
            "reported_results": (p.get("reported_results") or [])[:2],
        })
    figures = tables_figures.render_figures(proj, metrics)
    return {
        "idea": idea,
        "hypothesis": selected,
        "verdict": _verdict_summary(metrics, selected),
        "claims": _deterministic_claims(metrics),
        "tables": {"main": tables_figures.render_main_table(metrics)},
        "figures": [f.name for f in figures],
        "references": ref_entries,
        "evidence_pack": evidence.build_evidence_pack(metrics, selected),
    }


def _ws_root() -> Path:
    from services.research_harness.pipeline import WORKSPACE_ROOT
    return WORKSPACE_ROOT


# --------------------------------------------------------------------------- #
# LLM argumentative planning (1 call, validated)
# --------------------------------------------------------------------------- #


def _extract_json(text: str) -> dict[str, Any] | None:
    import re
    m = re.search(r"\{[\s\S]*\}", text or "")
    if not m:
        return None
    try:
        return json.loads(m.group(0))
    except json.JSONDecodeError:
        return None


def plan_blueprint(skeleton: dict[str, Any]) -> dict[str, Any]:
    """One LLM call: plan title direction, per-section narrative angles, and
    related-work thematic grouping. Validated against the skeleton — anything
    referencing unknown claim ids or markers is dropped (fallback: sensible
    deterministic ordering)."""
    claim_lines = "\n".join(f"- {c['id']} [{c['section']}]: {c['text_hint']}" for c in skeleton["claims"])
    ref_lines = "\n".join(
        f"- {r['marker']} ({r['year']}) {r['title']} | {r['abstract_digest'][:160]}"
        for r in skeleton["references"]
    )
    prompt = f"""你是论文写作规划师。基于以下真实实验蓝图，规划论文的论证结构。只输出一个 JSON 对象。

## 研究问题与结论
- idea: {skeleton['idea']}
- 假设: {json.dumps(skeleton.get('hypothesis') or {{}}, ensure_ascii=False)[:800]}
- 锚定结论: {json.dumps(skeleton['verdict'], ensure_ascii=False)}

## 可用论断（只能引用这些 id，数字已锚定）
{claim_lines}

## 可用文献（只能引用这些编号；每条附摘要片段）
{ref_lines}

## 输出 JSON 格式
{{
  "title_candidates": ["候选标题1（准确不夸大）", "候选标题2"],
  "sections": {{
    "introduction": {{"angle": "引言的论证角度", "claim_order": ["cmp_0", "sig_1"], "ref_markers": ["[1]", "[3]"]}},
    "related_work": {{"groupings": [{{"theme": "主题", "markers": ["[2]", "[5]"], "contrast": "这组工作与本文的差异（须含具体方法/数字，不得只罗列标题）"}}]}},
    "methods": {{"angle": "方法节如何组织", "must_explain": ["需要解释的机制/协议要点"]}},
    "experiments": {{"angle": "结果呈现顺序", "must_reference": ["表 1", "图 fig1_main_comparison.png"]}},
    "discussion": {{"angles": ["讨论点1", "讨论点2", "局限性要点"]}},
    "conclusion": {{"angle": "结论表述边界"}}
  }},
  "abstract_keywords": ["关键词1", "关键词2"]
}}

规则：related_work 每组 contrast 必须实质性（提到具体方法名或已发表数字）；ref_markers 只能用上面列出的编号；
claim_order 只能用上面列出的 id；负结果按负结果规划，禁止正面包装。"""
    try:
        content = get_message_content(chat([{"role": "user", "content": prompt}]))
    except Exception as exc:  # noqa: BLE001 — planning is best-effort; skeleton is the fallback
        logger.warning("[Blueprint] planning call failed, using deterministic order: %s", exc)
        return {}
    plan = _extract_json(content)
    if not isinstance(plan, dict):
        return {}
    # validate claim ids and ref markers against the skeleton
    valid_claims = {c["id"] for c in skeleton["claims"]}
    valid_markers = {r["marker"] for r in skeleton["references"]}
    for sec in (plan.get("sections") or {}).values():
        if isinstance(sec, dict) and isinstance(sec.get("claim_order"), list):
            sec["claim_order"] = [c for c in sec["claim_order"] if c in valid_claims]
        if isinstance(sec, dict) and isinstance(sec.get("ref_markers"), list):
            sec["ref_markers"] = [m for m in sec["ref_markers"] if m in valid_markers]
        for g in (sec.get("groupings") or []) if isinstance(sec, dict) else []:
            if isinstance(g, dict) and isinstance(g.get("markers"), list):
                g["markers"] = [m for m in g["markers"] if m in valid_markers]
    return plan


def build_blueprint(
    project_id: str,
    idea: str,
    selected: dict[str, Any],
    metrics: dict[str, Any],
    papers: list[dict[str, Any]],
    workspace_root: Path | None = None,
) -> Path:
    """Full blueprint: skeleton (deterministic) + plan (LLM, validated) →
    ``paper/blueprint.json``. Returns the blueprint path."""
    skeleton = build_skeleton(project_id, idea, selected, metrics, papers, workspace_root)
    plan = plan_blueprint(skeleton)
    skeleton["plan"] = plan
    root = Path(workspace_root) if workspace_root is not None else _ws_root()
    out = root / project_id / "paper" / "blueprint.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(skeleton, ensure_ascii=False, indent=2), encoding="utf-8")
    logger.info("[Blueprint] written %s (%d claims, %d refs, %d figures)",
                out, len(skeleton["claims"]), len(skeleton["references"]), len(skeleton["figures"]))
    return out
